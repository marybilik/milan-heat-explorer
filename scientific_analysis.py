"""## 23. Spatial Block Cross-Validation

Evaluates model error using spatially grouped folds to reduce leakage between nearby tracts. Spatial block MAPE is **2.07%**, compared with the naive random-split MAPE of **2.01%**.
"""

from sklearn.model_selection import GroupKFold
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_percentage_error

print("🔄 Spatial Block Cross-Validation\n")

# Create a 5-by-5 grid of spatial blocks
gdf_cv = merged.dropna(subset=['mean_lst', 'social_vulnerability',
                                'impervious_x', 'tree_cover_density']).copy()

# Assign tracts to blocks using their coordinates
gdf_cv['block_x'] = pd.qcut(gdf_cv.geometry.centroid.x, q=5, labels=False)
gdf_cv['block_y'] = pd.qcut(gdf_cv.geometry.centroid.y, q=5, labels=False)
gdf_cv['block'] = gdf_cv['block_x'].astype(str) + '_' + gdf_cv['block_y'].astype(str)

X = gdf_cv[['social_vulnerability', 'impervious_x', 'tree_cover_density']].values
y = gdf_cv['mean_lst'].values
groups = gdf_cv['block'].values

gkf = GroupKFold(n_splits=5)
mapes = []

for fold, (train_idx, test_idx) in enumerate(gkf.split(X, y, groups)):
    model = LinearRegression()
    model.fit(X[train_idx], y[train_idx])
    preds = model.predict(X[test_idx])
    mape = mean_absolute_percentage_error(y[test_idx], preds) * 100
    mapes.append(mape)
    print(f"  Fold {fold+1}: MAPE = {mape:.2f}%")

print(f"\n📊 HONEST MAPE (spatial CV): {np.mean(mapes):.2f}% ± {np.std(mapes):.2f}%")
print(f"📊 Naive MAPE (random split, old): 2.01%")
print(f"📊 Реальное падение точности: ~{(np.mean(mapes) - 2.01):.2f} п.п.")

